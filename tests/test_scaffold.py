@FRONTEND_PARAMS
def test_scaffold(tmp_path: Path, fe: str) -> None:
    d = make(tmp_path, fe)
    wrapper = (d / "src" / "project.v").read_text()
    # Same eight ports, in the same order and widths, as the Tiny Tapeout template.
    assert ports(wrapper) == tt_ports()
    assert len(tt_ports()) == 8
    assert "module tt_um_chip (" in wrapper
    assert "Generated by siliconsmith" in wrapper
    # Layout.
    assert (d / "build").is_dir()
    assert (d / ".siliconsmith").is_dir()
    core = d / ("src/chip.v" if fe == "verilog" else "hdl/chip.py")
    assert core.is_file()
    if fe != "verilog":
        assert not (d / "src" / "chip.v").exists()
    for rel in ("src/config.json", "test/tb.v", "test/Makefile", "test/requirements.txt"):
        assert (d / rel).is_file()
    assert (d / "docs" / "info.md").is_file()
    assert not (d / "spec.yaml").exists()  # arrives with M0-7
    # The project loads back.
    project = load_project(tmp_path, "chip")
    assert (project.name, project.frontend) == ("chip", fe)
    assert tomllib.loads((d / "siliconsmith.toml").read_text()) == {"name": "chip", "frontend": fe}


