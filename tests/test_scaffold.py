def test_scaffold_refuses_existing_project(tmp_path: Path) -> None:
    make(tmp_path, "verilog")
    with pytest.raises(ToolError, match="already exists"):
        make(tmp_path, "myhdl")
    (tmp_path / "other").symlink_to(tmp_path / "chip")
    with pytest.raises(ToolError, match="already exists"):
        make(tmp_path, "verilog", name="other")


def test_scaffold_bad_inputs(tmp_path: Path) -> None:
    with pytest.raises(ToolError, match="invalid project name"):
        create_project(tmp_path, "Bad Name", "verilog", "a", "d")
    with pytest.raises(ToolError, match="frontend"):
        create_project(tmp_path, "chip", "vhdl", "a", "d")
    assert list(tmp_path.iterdir()) == []


@pytest.mark.parametrize(
    ("field", "value", "needle"),
    [
        ("author", "", "empty"),
        ("author", "a\nb", "single line"),
        ("author", "a\x00b", "single line"),
        ("author", "a */ b", r"\*/"),
        ("author", "x" * 101, "limit"),
        ("description", "line1\r\nline2", "single line"),
        ("description", "x" * 201, "limit"),
        ("title", "t\x1b[0m", "single line"),
        ("title", "x" * 101, "limit"),
    ],
)
def test_scaffold_rejects_bad_text(tmp_path: Path, field: str, value: str, needle: str) -> None:
    args = {"author": "Ada", "description": "Desc", "title": "T"}
    args[field] = value
    with pytest.raises(ToolError, match=needle):
        create_project(tmp_path, "chip", "verilog", **args)  # type: ignore[arg-type]
    assert not (tmp_path / "chip").exists()


def tree_bytes(d: Path) -> dict[str, bytes]:
    return {str(p.relative_to(d)): p.read_bytes() for p in sorted(d.rglob("*")) if p.is_file()}


@FRONTEND_PARAMS
def test_scaffold_is_reproducible_and_path_free(tmp_path: Path, fe: str) -> None:
    root_a = tmp_path / "rootA"
    root_b = tmp_path / "elsewhere" / "rootB"
    root_a.mkdir()
    root_b.mkdir(parents=True)
    a = make(root_a, fe)
    b = make(root_b, fe)
    files_a = tree_bytes(a)
    assert files_a == tree_bytes(b)
    assert files_a  # not vacuous
    for rel, data in files_a.items():
        text = data.decode("utf-8")
        for needle in ("/home", "/work", "/tmp", str(root_a), str(root_b), str(tmp_path)):
            assert needle not in text, f"{needle!r} found in {rel}"
