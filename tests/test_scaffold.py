FRONTEND_PARAMS = pytest.mark.parametrize("fe", FRONTENDS)
PORT_RE = re.compile(r"^\s*(input|output)\s+wire\s+(\[7:0\])?\s*(\w+)\s*,?\s*(?://.*)?$", re.M)


def make(root: Path, fe: str, name: str = "chip") -> Path:
    project, _ = create_project(root, name, fe, "Ada Lovelace", "Adds two numbers.")
    return project.dir


def ports(verilog: str) -> list[tuple[str, str, str]]:
    """(direction, width, name) of the ports in the first module header."""
    header = verilog[verilog.index("module ") : verilog.index(");")]
    return [(d, w or "", n) for d, w, n in PORT_RE.findall(header)]


def tt_ports() -> list[tuple[str, str, str]]:
    return ports((TT_DIR / "src" / "project.v").read_text())


# --- the pinned snapshot -------------------------------------------------------------------


def test_upstream_hashes_match_snapshot() -> None:
    text = (TT_DIR / "UPSTREAM").read_text()
    listed = dict(
        (path, digest) for digest, path in re.findall(r"^  ([0-9a-f]{64})  (\S+)$", text, re.M)
    )
    actual = {
        str(p.relative_to(TT_DIR)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in TT_DIR.rglob("*")
        if p.is_file() and p.name != "UPSTREAM"
    }
    assert actual == listed
    assert re.search(r"^commit: [0-9a-f]{40}$", text, re.M)
    assert "repo: https://github.com/TinyTapeout/ttsky-verilog-template" in text


