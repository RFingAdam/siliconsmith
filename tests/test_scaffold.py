@FRONTEND_PARAMS
def test_scaffold_stubs_parse_and_have_entry_points(tmp_path: Path, fe: str) -> None:
    d = make(tmp_path, fe)
    test_tree = ast.parse((d / "test" / "test.py").read_text())
    test_src = (d / "test" / "test.py").read_text()
    assert "Covers: R1" in test_src
    assert 'unit="ns"' in test_src
    assert "int(dut.uo_out.value) == 50" in test_src
    assert "cocotb.start_soon" in test_src
    assert any(isinstance(n, ast.AsyncFunctionDef) for n in ast.walk(test_tree))
    if fe == "amaranth":
        tree = ast.parse((d / "hdl" / "chip.py").read_text())
        top = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "top"]
        assert len(top) == 1
        src = (d / "hdl" / "chip.py").read_text()
        assert 'm.domains.sync = cd = ClockDomain("sync")' in src
        assert "cd.rst.eq(~self.rst_n)" in src
    elif fe == "myhdl":
        tree = ast.parse((d / "hdl" / "chip.py").read_text())
        fn = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "chip"]
        assert len(fn) == 1
        assert [a.arg for a in fn[0].args.args] == [
            p for p in STUB_PORTS["myhdl"] if p in {a.arg for a in fn[0].args.args}
        ]
        assert any(isinstance(dec, ast.Name) and dec.id == "block" for dec in fn[0].decorator_list)
    else:
        core = (d / "src" / "chip.v").read_text()
        assert "module chip (" in core
        assert ports(core) == tt_ports()


