from __future__ import annotations

import pytest

from siliconsmith.wrapper import TT_PORTS, WrapperError, generate_wrapper

ALL = {port: direction for port, (direction, _) in TT_PORTS.items()}


def test_wrapper_full_core() -> None:
    text = generate_wrapper("chip", ALL, "Ada Lovelace")
    assert text.startswith("// SPDX-FileCopyrightText: Ada Lovelace\n")
    # REUSE-IgnoreStart
    assert "// SPDX-License-Identifier: Apache-2.0\n" in text
    # REUSE-IgnoreEnd
    assert "Generated by siliconsmith. Do not edit." in text
    assert "`default_nettype none" in text
    assert "module tt_um_chip (" in text
    assert "  chip core (" in text
    assert "_unused" not in text
    assert "assign" not in text
    assert text.endswith("endmodule\n")


def test_wrapper_subset_ties_off_outputs_and_lists_unused_inputs() -> None:
    core = {"ui_in": "input", "uo_out": "output"}
    text = generate_wrapper("chip", core, "Ada")
    assert ".ui_in(ui_in)," in text
    assert ".uo_out(uo_out)\n" in text
    assert "assign uio_out = 8'd0;" in text
    assert "assign uio_oe = 8'd0;" in text
    assert "assign uo_out" not in text
    assert "wire _unused = &{uio_in, ena, clk, rst_n, 1'b0};" in text


def test_wrapper_rejects_bad_name() -> None:
    from mcp.server.mcpserver.exceptions import ToolError

    with pytest.raises(ToolError, match="invalid project name"):
        generate_wrapper("x (input a); endmodule //", ALL, "Ada")


def test_wrapper_is_deterministic() -> None:
    assert generate_wrapper("chip", ALL, "Ada") == generate_wrapper("chip", dict(ALL), "Ada")


@pytest.mark.parametrize(
    ("core", "needle"),
    [
        ({"foo": "input"}, "not a Tiny Tapeout pin"),
        ({"ui_in": "output"}, "must be an input"),
        ({"uo_out": "input"}, "must be an output"),
    ],
)
def test_wrapper_validates_ports(core: dict[str, str], needle: str) -> None:
    with pytest.raises(WrapperError, match=needle):
        generate_wrapper("chip", core, "Ada")


def test_wrapper_validates_author() -> None:
    with pytest.raises(Exception, match="single line"):
        generate_wrapper("chip", ALL, "Ada\nLovelace")
