"""Generate the Tiny Tapeout wrapper `tt_um_<name>` around a core module `<name>`.

The wrapper has TT's fixed eight ports. It connects the core by name for the ports the core has,
ties the outputs the core does not drive to 0, and lists the inputs it does not use in an
`_unused` wire, the same way TT's own `project.v` does. This is a pure function: the same inputs
always give the same text.

This module is stdlib-only because it runs in two places: on the host (through
`siliconsmith.wrapper`, which validates the name and author first) and inside the container (the
`emit` verb), and both must produce identical bytes.
"""

from __future__ import annotations

from collections.abc import Mapping

# name -> (direction, width). The order is the order of the ports in the wrapper.
TT_PORTS: dict[str, tuple[str, int]] = {
    "ui_in": ("input", 8),
    "uo_out": ("output", 8),
    "uio_in": ("input", 8),
    "uio_out": ("output", 8),
    "uio_oe": ("output", 8),
    "ena": ("input", 1),
    "clk": ("input", 1),
    "rst_n": ("input", 1),
}

_COMMENTS = {
    "ui_in": "Dedicated inputs",
    "uo_out": "Dedicated outputs",
    "uio_in": "IOs: Input path",
    "uio_out": "IOs: Output path",
    "uio_oe": "IOs: Enable path (active high: 0=input, 1=output)",
    "ena": "always 1 when the design is powered, so you can ignore it",
    "clk": "clock",
    "rst_n": "reset_n - low to reset",
}


class WrapperError(ValueError):
    """The core's ports do not fit the Tiny Tapeout pin set."""


def check_core_ports(ports: Mapping[str, tuple[str, int]]) -> list[str]:
    """Problems with a core's ports (`name -> (direction, width)`) against the TT pin set."""
    problems = []
    for port, (direction, width) in ports.items():
        if port not in TT_PORTS:
            problems.append(
                f"port {port!r} is not a Tiny Tapeout pin; allowed: {', '.join(TT_PORTS)}"
            )
            continue
        want_direction, want_width = TT_PORTS[port]
        if direction != want_direction:
            problems.append(f"port {port!r} must be an {want_direction}, not an {direction}")
        elif width != want_width:
            problems.append(f"port {port!r} must be {want_width} bit(s) wide, not {width}")
    return problems


def generate_wrapper(name: str, core_ports: Mapping[str, str], author: str) -> str:
    """Return the text of `src/project.v`. The caller has validated `name` and `author`.

    `core_ports` maps each port name of the core module to its direction (`input` or `output`).
    Names and directions must match the TT pin set; widths are checked elsewhere (from Yosys).
    """
    for port, direction in core_ports.items():
        if port not in TT_PORTS:
            raise WrapperError(
                f"core port {port!r} is not a Tiny Tapeout pin; allowed: {', '.join(TT_PORTS)}"
            )
        if direction != TT_PORTS[port][0]:
            raise WrapperError(
                f"core port {port!r} must be an {TT_PORTS[port][0]}, not an {direction}"
            )
    lines = [
        f"// SPDX-FileCopyrightText: {author}",
        # REUSE-IgnoreStart
        "// SPDX-License-Identifier: Apache-2.0",
        # REUSE-IgnoreEnd
        "// Generated by siliconsmith. Do not edit.",
        "",
        "`default_nettype none",
        "",
        f"module tt_um_{name} (",
    ]
    decls = []
    for port, (direction, width) in TT_PORTS.items():
        kind = "input " if direction == "input" else "output"
        vec = "[7:0]" if width == 8 else "     "
        decls.append(f"    {kind} wire {vec} {port}")
    # Same shape as the template: commas after every port but the last, comments aligned.
    pad = max(len(d) for d in decls) + 2
    for index, (decl, port) in enumerate(zip(decls, TT_PORTS, strict=True)):
        comma = "," if index < len(decls) - 1 else " "
        lines.append(f"{decl + comma:<{pad}} // {_COMMENTS[port]}")
    lines += [");", ""]
    connected = [p for p in TT_PORTS if p in core_ports]
    lines.append(f"  {name} core (")
    for index, port in enumerate(connected):
        comma = "," if index < len(connected) - 1 else ""
        lines.append(f"      .{port}({port}){comma}")
    lines += ["  );", ""]
    undriven = [p for p, (d, _) in TT_PORTS.items() if d == "output" and p not in core_ports]
    if undriven:
        lines.append("  // The core does not drive these outputs, so they are tied to 0.")
        lines += [f"  assign {port} = 8'd0;" for port in undriven]
        lines.append("")
    unused = [p for p, (d, _) in TT_PORTS.items() if d == "input" and p not in core_ports]
    if unused:
        lines.append("  // List all unused inputs to prevent warnings")
        lines.append(f"  wire _unused = &{{{', '.join(unused)}, 1'b0}};")
        lines.append("")
    lines += ["endmodule", ""]
    return "\n".join(lines)
